"""Emit the isolated-pair gates after validating the round-invariant graph."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
N = 112


def adjacency():
    geometry = json.loads((ROOT / "data/geometry.json").read_text())
    actual, stencil = set(), [set() for _ in range(N)]
    for a, b, logical, _ in geometry["edges"]:
        if logical:
            raise ValueError("Paired edges must preserve the logical frame.")
        actual.add((a, b))
        ta, x = divmod(a, N)
        tb, y = divmod(b, N)
        stencil[x].add((tb - ta, y))
        stencil[y].add((ta - tb, x))
    generated = set()
    for t in range(16):
        for x, adjacent in enumerate(stencil):
            for dt, y in adjacent:
                if 0 <= t + dt < 16:
                    generated.add(tuple(sorted((t * N + x, (t + dt) * N + y))))
    if generated != actual:
        raise ValueError("One-hop adjacency depends on the extraction round.")
    return [sorted(row) for row in stencil]


def write(adj):
    near = ("prev", "cur", "following")
    header = "    input wire [111:0] prev, cur, following, output wire [111:0] result\n);\n"
    degree, drop = "module qec_degree_one(\n" + header, "module qec_drop_pairs(\n" + header
    for center, row in enumerate(adj):
        terms = [f"{near[dt + 1]}[{b}]" for dt, b in row]
        left, right = " | ".join(terms[:len(terms)//2]), " | ".join(terms[len(terms)//2:])
        level = [(term, "1'b0") for term in terms]
        while len(level) > 1:
            combined = []
            key = len(level)
            for i in range(0, key - 1, 2):
                a, b = level[i], level[i+1]
                first, twice = f"a_{center}_{key}_{i}", f"m_{center}_{key}_{i}"
                degree += f"    wire {first} = {a[0]} | {b[0]};\n"
                degree += f"    wire {twice} = {a[1]} | {b[1]} | ({a[0]} & {b[0]});\n"
                combined.append((first, twice))
            if key % 2:
                combined.append(level[-1])
            level = combined
        degree += f"    assign result[{center}] = cur[{center}] & {level[0][0]} & ~{level[0][1]};\n"
        drop += f"    assign result[{center}] = cur[{center}] & (({left}) | ({right}));\n"
    (ROOT / "rtl/qec_prune_gates.v").write_text(
        "// Generated by gen_stencil.py from the finite detector graph.\n" + degree + "endmodule\n\n" +
        drop + "endmodule\n"
    )


if __name__ == "__main__":
    write(adjacency())
